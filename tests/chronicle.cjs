const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
 const page=await browser.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));let checks=0;
 const ok=(v,m)=>{assert(v,m);checks++};
 await page.goto('http://127.0.0.1:8000');
 const seed={schema:1,extra:{keep:true},workouts:[{id:'later',date:'2026-02-02',km:600,type:'Bieg',minutes:80,notes:'notatka '.repeat(600)},{id:'first',date:'2026-01-01',km:400,type:'Marsz',custom:'keep'}]};
 await page.evaluate(d=>{data=d;localStorage.setItem(KEY,JSON.stringify(d));setView('chronicle')},seed);
 for(const width of [320,375,390,430,768]){
  await page.setViewportSize({width,height:844});
  ok(await page.locator('.milestone-profile').count()===20,'all locations');
  ok(await page.locator('.milestone-profile .chronicle-trigger[aria-expanded="true"]').count()===0,'collapsed by default');
  const buttons=page.locator('.milestone-profile .chronicle-trigger');
  await buttons.nth(0).click();await page.waitForTimeout(300);
  ok(await buttons.nth(0).getAttribute('aria-expanded')==='true','open');
  ok(await page.locator('#place-19').evaluate(e=>!e.inert&&e.clientHeight>=e.firstElementChild.scrollHeight-1),'full content fits');
  await buttons.nth(1).click();await page.waitForTimeout(300);
  ok(await buttons.nth(0).getAttribute('aria-expanded')==='false','accordion closes previous');
  await buttons.nth(1).focus();await page.keyboard.press('Enter');await page.waitForTimeout(300);
  ok(await buttons.nth(1).getAttribute('aria-expanded')==='false','keyboard close');
  await page.locator('.journal-entry .chronicle-trigger').first().click();await page.waitForTimeout(300);
  ok(await page.locator('#journal-0').evaluate(e=>e.clientHeight>=e.firstElementChild.scrollHeight-1),'long journal uncut');
  ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no horizontal overflow '+width);
  await page.locator('.journal-entry .chronicle-trigger').first().click();
 }
 ok(await page.locator('.profile-name').first().textContent()==='Góra Przeznaczenia','descending distance');
 ok(await page.locator('#place-19 time').getAttribute('datetime')==='2026-02-02','derived chronological discovery');
 ok(await page.locator('#place-0 time').count()===0,'no invented start date');
 ok(await page.evaluate(()=>JSON.stringify(JSON.parse(localStorage.getItem(KEY)))===JSON.stringify(data)),'no stored data changed');
 await page.emulateMedia({reducedMotion:'reduce'});
 ok(await page.locator('.chronicle-body').first().evaluate(e=>getComputedStyle(e).transitionDuration)==='0s','reduced motion');
 await page.evaluate(()=>{data.workouts=[];save()});
 ok(await page.locator('.journal-entry').count()===0,'empty journal');
 ok(await page.locator('.milestone-profile').count()===1,'existing start discovery preserved');
 ok(await page.locator('.chronicle-stats dd').nth(2).textContent()==='0','stats after deletion');
 await page.evaluate(()=>{data.workouts.push({id:'new',date:'2026-01-01',km:100,type:'Marsz'});save()});
 ok(await page.locator('.chronicle-stats dd').nth(2).textContent()==='1','stats after addition');
 ok(await page.locator('.milestone-profile').count()===3,'discoveries update');
 ok(await page.locator('.chronicle-page img[src*="lothlorien"]').count()===0,'locked art absent');
 await page.evaluate(()=>{data.workouts=Array.from({length:9},(_,i)=>({id:'entry-'+i,date:'2026-01-'+String(i+1).padStart(2,'0'),km:1,type:'Marsz'}));save()});
 ok(await page.locator('.journal-entry').count()===6,'journal initially limited');
 await page.locator('#journalToggle').click();ok(await page.locator('.journal-entry').count()===9,'show all entries');
 await page.locator('#journalToggle').scrollIntoViewIfNeeded();
 ok(await page.locator('#journalToggle').evaluate(e=>e.getBoundingClientRect().bottom<=document.querySelector('.bottom').getBoundingClientRect().top),'last control above bottom navigation');
 await page.locator('#journalToggle').click();ok(await page.locator('.journal-entry').count()===6,'show fewer entries');
 ok(errors.length===0,errors.join(';'));
 console.log('PASS Chronicle: '+checks+' checks at 320, 375, 390, 430, 768 px');await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
